# --------------------------------------------------------------------------- cached resources


@st.cache_resource(show_spinner="Loading index...")
def get_pipeline(data_dir: str, index_dir: str, embedder: str, built_at: str) -> Any:
    """One pipeline per (data dir, index dir, embedder, build time); reused by every session.

    Chroma caches its client per path, so the store must be opened once per process. ``built_at`` (the
    manifest's created_at) invalidates the cache after a rebuild.
    """
    from ehr_rag.pipeline import EHRRagPipeline
    from ehr_rag.generation import ExtractiveGenerator

    settings = load_settings(data_dir=data_dir, index_dir=index_dir, embedder=embedder)
    # The generator is chosen per request (see S.ask_with_generator); load never builds a Claude client.
    return EHRRagPipeline.load(settings, generator=ExtractiveGenerator())


@st.cache_resource(show_spinner=False)
def get_generator(llm: str, model: str, effort: str, max_tokens: int, fallbacks: bool) -> Any:
    settings = load_settings(claude_model=model, claude_effort=effort, claude_max_tokens=max_tokens,
                             claude_fallbacks=fallbacks)
    return S.make_generator(settings, llm)


@st.cache_data(show_spinner=False)
def get_examples(data_dir: str, patient_id: str, built_at: str, _patient_text: str) -> list[dict]:
    facts = S.PatientFacts.from_data_dir(Path(data_dir), patient_id)
    return [vars(q) for q in S.example_questions(facts, _patient_text)]


@st.cache_resource(show_spinner="Projecting embeddings (PCA)...")
def get_projection(_pipe: Any, cache_key: str, scope_patient: Optional[str]) -> S.Projection:
    chunks, vectors = _pipe.store.get_embeddings(scope_patient)
    return S.project_chunks(chunks, vectors, seed=0)


@st.cache_data(show_spinner=False)
def get_report_list(reports_dir: str, _stamp: tuple) -> list[dict]:
    return S.list_reports(Path(reports_dir))


@st.cache_data(show_spinner=False)
def get_report(path: str, mtime: float) -> dict:
    return S.load_report(Path(path))


# --------------------------------------------------------------------------- small helpers


def _code_block(commands: list[str]) -> None:
    st.code("\n".join(commands), language="bash")


def _fmt(value: Any, digits: int = 2) -> str:
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return "n/a"
    return f"{value:.{digits}f}" if isinstance(value, float) else str(value)


def _table(df: pd.DataFrame, status_col: Optional[str] = None) -> None:
    """Render ``df`` as an HTML table (``st.dataframe`` needs pyarrow, which is unusable with numpy<2 here)."""
    st.markdown(S.html_table(df, status_cols=(status_col,) if status_col else ()), unsafe_allow_html=True)


def _setup_error(settings: Settings, problem: str, embedder: str = "tfidf") -> None:
    st.error(f"{problem}\n\nRun this from the project root, then reload the page:")
    _code_block(S.setup_commands(settings, embedder))


