def _use_example(question: str) -> None:
    st.session_state["question"] = question
    st.session_state["run_pending"] = True


def _current_result() -> Optional[dict]:
    res = st.session_state.get("result")
    if res and res["patient_id"] == patient_id and res["embedder"] == embedder:
        return res
    return None


